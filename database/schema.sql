CREATE TABLE usuario (
    id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre   VARCHAR2(100) NOT NULL,
    correo   VARCHAR2(100) NOT NULL,
    rol      VARCHAR2(30)  NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_correo UNIQUE (correo)
);

CREATE TABLE espacio (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR2(100) NOT NULL,
    tipo       VARCHAR2(50)  NOT NULL,
    capacidad  NUMBER(5)     NOT NULL,
    CONSTRAINT pk_espacio PRIMARY KEY (id),
    CONSTRAINT uk_espacio_nombre UNIQUE (nombre),
    CONSTRAINT ck_espacio_capacidad CHECK (capacidad > 0)
);

CREATE TABLE horario (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    espacio_id   NUMBER NOT NULL,
    dia_semana   VARCHAR2(20) NOT NULL,
    hora_inicio  TIMESTAMP NOT NULL,
    hora_fin     TIMESTAMP NOT NULL,
    CONSTRAINT pk_horario PRIMARY KEY (id),
    CONSTRAINT fk_horario_espacio FOREIGN KEY (espacio_id) REFERENCES espacio (id) ON DELETE CASCADE,
    CONSTRAINT ck_horario_horas CHECK (hora_inicio < hora_fin),
    CONSTRAINT uk_horario UNIQUE (espacio_id, dia_semana, hora_inicio, hora_fin)
);

CREATE TABLE reserva (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    usuario_id   NUMBER NOT NULL,
    espacio_id   NUMBER NOT NULL,
    fecha        DATE NOT NULL,
    hora_inicio  TIMESTAMP NOT NULL,
    hora_fin     TIMESTAMP NOT NULL,
    estado       VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    motivo       VARCHAR2(255),
    CONSTRAINT pk_reserva PRIMARY KEY (id),
    CONSTRAINT fk_reserva_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_reserva_espacio FOREIGN KEY (espacio_id) REFERENCES espacio (id) ON DELETE CASCADE,
    CONSTRAINT ck_reserva_horas CHECK (hora_inicio < hora_fin)
);

CREATE INDEX ix_horario_espacio_dia ON horario (espacio_id, dia_semana);
CREATE INDEX ix_reserva_espacio_fecha ON reserva (espacio_id, fecha);
CREATE INDEX ix_reserva_usuario ON reserva (usuario_id);
CREATE INDEX ix_reserva_fecha ON reserva (fecha);
